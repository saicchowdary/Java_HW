package Week1;

public class Day1_Task2_Variables {

    public static void main(String[] args) {

        // int - whole number
        int testCases = 20;

        // double - decimal number
        double passPercentage = 85.5;

        // char - single character
        char grade = 'A';

        // boolean - true or false
        boolean testPassed = true;

        // String - text
        String testerName = "Deep Chandu";

        System.out.println("Tester Name: " + testerName);
        System.out.println("Test Cases: " + testCases);
        System.out.println("Pass Percentage: " + passPercentage);
        System.out.println("Grade: " + grade);
        System.out.println("Test Passed: " + testPassed);

        // Updating variable
        testCases = 25;

        System.out.println("Updated Test Cases: " + testCases);
    }
}