package Week7;

public class Day2_Task3_StatusCodes {

    public static void main(String[] args) {

        System.out.println("Week 7 Day 2 - Task 3");
        System.out.println("HTTP Status Code Validation");

        // 200 OK
        System.out.println("\n200 OK");
        System.out.println("Request completed successfully.");

        // 201 Created
        System.out.println("\n201 Created");
        System.out.println("New resource created successfully.");

        // 400 Bad Request
        System.out.println("\n400 Bad Request");
        System.out.println("Server cannot process an invalid request.");

        // 404 Not Found
        System.out.println("\n404 Not Found");
        System.out.println("Requested resource was not found.");

        System.out.println("\nStatus Code Practice Completed!");

    }
}
